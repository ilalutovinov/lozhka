const hash = (s) => { let h = 2166136261; for (const c of s) { h ^= c.charCodeAt(0); h = Math.imul(h, 16777619); } return h >>> 0; };

// [{store: id, ing: название, price}] — детерминированный разброс ±6 %, чтобы цены в магазинах отличались
export function buildPrices() {
  const out = [];
  STORES.forEach((s) => INGREDIENTS.forEach((i) => {
    const jitter = 1 + ((hash(s.name + i.name) % 13) - 6) / 100;
    out.push({ store: s.id, ing: i.name, price: Math.round(i.base * CATM[s.type][i.category] * s.mult * jitter * 100) / 100 });
  }));
  return out;
}

